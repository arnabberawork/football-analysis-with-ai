"""Builds the blind tactical-insight rating sheets from experiment/results/main_comparison.csv.
Run: uv run python experiment/tactical_eval/make_kit.py  (needs openpyxl)"""
import csv, random
from pathlib import Path
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill, Border, Side
from openpyxl.worksheet.datavalidation import DataValidation

HERE = Path(__file__).resolve().parent
SRC = str(HERE.parent / 'results') + '/'
rows = list(csv.DictReader(open(SRC + 'main_comparison.csv', encoding='utf-8')))
eda = {x['match_id']: x for x in csv.DictReader(open(SRC + 'dataset_eda.csv'))}
pairs = {}
for x in rows:
    if x['query'].startswith('Summarize'):
        pairs.setdefault(x['match_id'], {})[x['system']] = x
STAGE_ORDER = ['Group Stage', 'Round of 16', 'Quarter-finals', 'Semi-finals', '3rd Place Final', 'Final']
items = []
for m, v in pairs.items():
    if min(len(v['naive']['response_text']), len(v['agentic']['response_text'])) < 200:
        continue  # baseline refused ("Not enough information") - no tactics to compare
    e = eda[m]
    items.append((STAGE_ORDER.index(e['stage']), m, e, v))
items.sort()
rng = random.Random(2026)
_order = ['agentic'] * (len(items) // 2) + ['naive'] * (len(items) - len(items) // 2)
rng.shuffle(_order)
key = []
DIMS = ['tactical_relevance', 'tactical_correctness', 'evidence_support', 'depth']
DIM_LABEL = {'tactical_relevance': 'Tactical relevance', 'tactical_correctness': 'Tactical correctness',
             'evidence_support': 'Evidence support', 'depth': 'Depth of analysis'}
sheet_rows = []
for pid, (_, m, e, v) in enumerate(items):
    a = _order[pid]; b = 'naive' if a == 'agentic' else 'agentic'
    key.append({'pair_id': pid, 'match_id': m, 'a_system': a, 'b_system': b})
    match = f"{e['stage']}: {e['home_team']} {e['home_score']}-{e['away_score']} {e['away_team']} ({e['date']})" + (' - decided on penalties' if e['went_to_penalties'] == 'True' else '')
    sheet_rows.append([pid, match, v[a]['query'], v[a]['reference_summary'], v[a]['response_text'], v[b]['response_text']])

with open(HERE / 'tactical_eval_key.csv', 'w', newline='', encoding='utf-8') as f:
    w = csv.DictWriter(f, fieldnames=['pair_id', 'match_id', 'a_system', 'b_system']); w.writeheader(); w.writerows(key)

thin = Side(style='thin', color='A6A6A6')
HEAD = ['pair_id', 'match', 'query', 'match_facts (official record)', 'response_A', 'response_B'] + \
       [f'A_{d}' for d in DIMS] + [f'B_{d}' for d in DIMS] + ['preferred (A/B/Tie)', 'comments']
WID = [7, 30, 22, 45, 70, 70] + [12] * 8 + [12, 30]

RUBRIC = [
    ('Tactical relevance', 'Does the response discuss how the teams played (shape, pressing, build-up, transitions, set pieces, momentum shifts) rather than only listing events?',
     '1 = no tactical content; 3 = some tactical remarks, partly generic; 5 = clearly explains how and why the match unfolded tactically'),
    ('Tactical correctness', 'Are the tactical claims plausible and consistent with the match facts and with what actually happened in the match?',
     '1 = tactical claims are wrong or contradict the facts; 3 = mostly plausible with some doubtful claims; 5 = all tactical claims are correct and consistent'),
    ('Evidence support', 'Are the tactical claims backed by specific events (minutes, players, actions) in the response?',
     '1 = claims are unsupported generalities; 3 = some claims supported; 5 = every main claim is tied to specific events'),
    ('Depth of analysis', 'Does the response go beyond description to explain causes and effects (e.g. why a team took control, what changed after a substitution)?',
     '1 = purely descriptive; 3 = some explanation; 5 = insightful explanation a coach or analyst would find useful'),
]


def build(path):
    wb = Workbook()
    ins = wb.active; ins.title = 'Instructions'
    ins.column_dimensions['A'].width = 24; ins.column_dimensions['B'].width = 70; ins.column_dimensions['C'].width = 70
    lines = [
        ['Tactical-insight evaluation (blind)'],
        ['You will see 13 match summaries generated by two different systems (Response A and Response B) for the same question. You are not told which system produced which response, and the order is random.'],
        ['For each pair: read the match facts, then both responses. Score EACH response from 1 (poor) to 5 (excellent) on the four dimensions below, then say which response you prefer overall for tactical insight (A, B or Tie).'],
        ['Judge only tactical quality on these four dimensions. Do not reward length or writing style. Use the match facts and your own knowledge of the match to judge correctness.'],
        ['Work independently: do not discuss your scores with the other raters. Expected time: about 60-75 minutes.'],
        [''],
        ['Dimension', 'Question to ask', 'Scale anchors'],
    ] + [list(r) for r in RUBRIC]
    for r in lines:
        ins.append(r)
    ins['A1'].font = Font(bold=True, size=14)
    for c in ins[7]:
        c.font = Font(bold=True); c.fill = PatternFill('solid', fgColor='D9E2F3')
    for row in ins.iter_rows():
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical='top')
    for r in range(2, 6):
        ins.merge_cells(start_row=r, start_column=1, end_row=r, end_column=3)
        ins.row_dimensions[r].height = 32

    ws = wb.create_sheet('Ratings')
    ws.append(HEAD)
    for i, w in enumerate(WID, 1):
        ws.column_dimensions[ws.cell(1, i).column_letter].width = w
    for c in ws[1]:
        c.font = Font(bold=True); c.fill = PatternFill('solid', fgColor='D9E2F3')
        c.alignment = Alignment(wrap_text=True, vertical='center', horizontal='center')
    for r in sheet_rows:
        ws.append(r + [None] * 10)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical='top')
            c.border = Border(top=thin, bottom=thin, left=thin, right=thin)
        for c in row[6:14]:
            c.fill = PatternFill('solid', fgColor='FFF2CC'); c.alignment = Alignment(horizontal='center', vertical='top')
        row[14].fill = PatternFill('solid', fgColor='FFF2CC')
        row[15].fill = PatternFill('solid', fgColor='FFF2CC')
    for r in range(2, len(sheet_rows) + 2):
        ws.row_dimensions[r].height = 400
    ws.freeze_panes = 'E2'
    n = len(sheet_rows) + 1
    dv = DataValidation(type='whole', operator='between', formula1='1', formula2='5', showErrorMessage=True,
                        errorTitle='Score 1-5', error='Enter a whole number from 1 to 5.')
    ws.add_data_validation(dv); dv.add(f'G2:N{n}')
    dv2 = DataValidation(type='list', formula1='"A,B,Tie"', allow_blank=True)
    ws.add_data_validation(dv2); dv2.add(f'O2:O{n}')
    wb.save(path)


for k in (1, 2, 3):
    build(HERE / f'tactical_eval_sheet_rater{k}.xlsx')
print(len(sheet_rows), 'pairs;', sum(1 for k in key if k['a_system'] == 'agentic'), 'with agentic as A')
